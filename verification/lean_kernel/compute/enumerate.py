"""Enumeration of the vertices of R (d = 4) up to Gamma, with the rays of each vertex cone taken up to the
automorphisms of the vertex.

For T in Aut(J) (T^T J T = J, T in Gamma) the map Y -> T^T Y T permutes the extreme rays of the cone C_J and
carries the edge J + tY onto the edge J + t T^T Y T, with the same t* and an equivalent end point; det J and
det Q along the two edges agree.  So one ray per orbit of the group generated by any set of automorphisms
suffices.  The orbits are computed in integer arithmetic; every image is checked to be a ray of the list."""
import sys, json, time
from fractions import Fraction as F
import numpy as np
from forms import frac_mat, min_vectors, sym_from_vec, vec_from_sym, blocks, det, rank, sym_coords
from rays import extreme_rays
from edges import tstar
from unbounded import classify
from equiv import invariant, isometries, automorphisms, act

N = 5
D = N * (N + 1) // 2

def fstr(M):
    return [[str(x) for x in row] for row in M]

def sym_action(T):
    """15 x 15 integer matrix of y -> vec(T^T sym(y) T)."""
    A = np.zeros((D, D), dtype=np.int64)
    for c in range(D):
        e = [0] * D
        e[c] = 1
        img = vec_from_sym(act(T, sym_from_vec(e, N)))
        for r in range(D):
            assert img[r].denominator == 1
            A[r, c] = int(img[r])
    return A

def generators(J, mv, seeds=12, per_seed=2):
    gens = []
    seen = set()
    for s in range(seeds):
        for T in automorphisms(J, mv, limit=per_seed, shuffle_seed=s):
            key = tuple(map(tuple, T))
            if key not in seen:
                seen.add(key)
                gens.append(T)
    return gens

def orbits(rays, gens):
    """representatives (index, orbit size) of the orbits of <gens> on the rays."""
    R = np.array(rays, dtype=np.int64)
    idx = {tuple(r): i for i, r in enumerate(rays)}
    parent = list(range(len(rays)))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    for T in gens:
        A = sym_action(T)
        img = R @ A.T
        for i in range(len(rays)):
            j = idx[tuple(int(x) for x in img[i])]      # KeyError if the image is not a ray
            a, b = find(i), find(j)
            if a != b:
                parent[a] = b
    size = {}
    first = {}
    for i in range(len(rays)):
        r = find(i)
        size[r] = size.get(r, 0) + 1
        first.setdefault(r, i)
    return sorted((first[r], size[r]) for r in size)

def main(out):
    J51 = frac_mat([[4, 0, 0, 0, 2], [0, 4, 0, 0, -2], [0, 0, 4, 0, -2], [0, 0, 0, 4, -2], [2, -2, -2, -2, 4]])
    verts = []
    bykey = {}

    def add_vertex(J, mv, inv):
        verts.append({'J': J, 'mv': mv, 'inv': inv})
        bykey.setdefault(inv, []).append(len(verts) - 1)
        return len(verts) - 1

    def lookup(J, mv, inv):
        for i in bykey.get(inv, []):
            T = isometries(verts[i]['J'], J, verts[i]['mv'], mv, first=True)
            if T:
                return i, T[0]
        return None, None

    mv0 = min_vectors(J51)
    add_vertex(J51, mv0, invariant(J51, mv0))
    report = []
    i = 0
    t_start = time.time()
    while i < len(verts):
        V = verts[i]
        J, mv = V['J'], V['mv']
        assert rank([sym_coords(k) for k in mv]) == D, "not a vertex"
        t0 = time.time()
        R = extreme_rays(mv)
        gens = generators(J, mv)
        reps = orbits(R, gens)
        edges = []
        for ri, osize in reps:
            y = R[ri]
            Y = sym_from_vec(y, N)
            c, w = classify(Y)
            if c == 'unbounded':
                edges.append({'ray': list(y), 'orbit': osize, 'tstar': None})
                continue
            ts = tstar(J, Y, w)
            M = [[J[a][b] + ts * Y[a][b] for b in range(N)] for a in range(N)]
            mvM = min_vectors(M)
            inv = invariant(M, mvM)
            j, T = lookup(M, mvM, inv)
            if j is None:
                j = add_vertex(M, mvM, inv)
                T = [[1 if a == b else 0 for b in range(N)] for a in range(N)]
            edges.append({'ray': list(y), 'orbit': osize, 'tstar': str(ts), 'to': j, 'T': T})
        Q, r, s = blocks(J)
        rec = {'index': i, 'J': fstr(J), 'detQ': str(det(Q)), 'detJ': str(det(J)),
               'nmin': len(mv), 'nrays': len(R), 'ngens': len(gens),
               'gens': gens, 'edges': edges}
        report.append(rec)
        nb = sorted({e['to'] for e in edges if e['tstar'] is not None})
        print(f"vertex {i}: detQ={det(Q)} detJ={det(J)} |Min|={len(mv)} rays={len(R)} orbits={len(reps)} "
              f"unbounded={sum(e['orbit'] for e in edges if e['tstar'] is None)} neighbours={nb} "
              f"[{time.time() - t0:.1f}s, total {len(verts)} vertices]", flush=True)
        with open(out, 'w') as fh:
            json.dump(report, fh)
        i += 1
    print(f"done: {len(verts)} vertices in {time.time() - t_start:.0f}s")

if __name__ == '__main__':
    main(sys.argv[1])
